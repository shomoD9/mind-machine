#!/usr/bin/env python3
"""Generate the three native Xcode targets without an external generator.
Run from any directory. Xcode consumes the project and shared schemes; source
files stay in Apps and the local Swift package supplies shared core/UI modules.
"""
from pathlib import Path
import hashlib
import json
import plistlib

ROOT = Path(__file__).resolve().parents[1]
OBJECTS = {}


def narrated_plist(values, purpose):
    """Keep generated configuration self-describing where Xcode consumes it."""
    content = plistlib.dumps(values, sort_keys=False)
    comment = ("<!-- " + purpose + " Generated by Scripts/generate_project.py. -->\n").encode()
    return content.replace(b'<plist version="1.0">', comment + b'<plist version="1.0">', 1)


def ident(name):
    """Stable object IDs keep regeneration reviewable in Git."""
    return hashlib.sha1(name.encode()).hexdigest()[:24].upper()


def quote(value):
    return json.dumps(str(value))


def add(object_name, isa, **fields):
    """Store OpenStep fragments; values are already encoded by their caller."""
    key = ident(object_name)
    OBJECTS[key] = {'isa': isa, **fields}
    return key


def array(values):
    return '(' + ', '.join(values) + (',' if values else '') + ')'


def dictionary(values):
    return '{ ' + ' '.join(f'{k} = {v};' for k, v in values.items()) + ' }'


# One xcconfig supplies signing and capability identifiers to all three targets. The iPhone and Mac apps share
# one bundle ID (universal purchase: one App Store Connect record); only the keyboard extension has its own suffix.
# Command-line CODE_SIGNING_ALLOWED=NO keeps CI independent of a paid team.
signing_config = add("signingConfig", "PBXFileReference", lastKnownFileType="text.xcconfig", path=quote("Config/MindMachine.xcconfig"), sourceTree=quote("<group>"))
package = add('package', 'XCLocalSwiftPackageReference', relativePath=quote('.'))
# Pure pill logic (state machine, geometry, persistence) lives in its own package so CI can test it; only the Mac target links it.
pill_package = add('pillPackage', 'XCLocalSwiftPackageReference', relativePath=quote('Pill'))
products = []
targets = []
groups = []
for name, folder, bundle, kind in [
    ('MindMachine', 'iOS', '$(MINDMACHINE_BUNDLE_ID)', 'application'),
    ('MindMachineKeyboard', 'Keyboard', '$(MINDMACHINE_KEYBOARD_BUNDLE_ID)', 'app-extension'),
    ('MindMachineMac', 'Mac', '$(MINDMACHINE_BUNDLE_ID)', 'application'),
]:
    is_mac = folder == 'Mac'
    files = sorted((ROOT/'Apps'/folder).glob('*.swift'))
    if not is_mac:
        files += sorted((ROOT/'Apps'/'Shared').glob('*.swift'))
    sources = []
    refs = []
    for path in files:
        rel = path.relative_to(ROOT).as_posix()
        ref = add(name+rel+'ref', 'PBXFileReference', lastKnownFileType='sourcecode.swift', path=quote(rel), sourceTree=quote('<group>'))
        refs.append(ref)
        sources.append(add(name+rel, 'PBXBuildFile', fileRef=ref))
    # App icons and the Mac menu-bar template must be compiled/copied as bundle resources.
    # The keyboard extension deliberately has no asset catalog or app icon.
    resources = []
    for resource, file_type in [('Assets.xcassets', 'folder.assetcatalog'), ('menubar-template.svg', 'image.svg')]:
        path = ROOT/'Apps'/folder/resource
        if path.exists():
            ref = add(name+resource+'ref', 'PBXFileReference', lastKnownFileType=file_type, path=quote(path.relative_to(ROOT).as_posix()), sourceTree=quote('<group>'))
            refs.append(ref)
            resources.append(add(name+resource, 'PBXBuildFile', fileRef=ref))
    resource_phase = add(name+'resources', 'PBXResourcesBuildPhase', buildActionMask='2147483647', files=array(resources), runOnlyForDeploymentPostprocessing='0')
    groups.append(add(name+'group', 'PBXGroup', name=quote(name), children=array(refs), sourceTree=quote('<group>')))
    source_phase = add(name+'sources', 'PBXSourcesBuildPhase', buildActionMask='2147483647', files=array(sources), runOnlyForDeploymentPostprocessing='0')
    dependencies = []
    links = []
    for module in ['MindMachineCore', 'MindMachineUI']:
        dependency = add(name+module, 'XCSwiftPackageProductDependency', package=package, productName=quote(module))
        dependencies.append(dependency)
        links.append(add(name+module+'link', 'PBXBuildFile', productRef=dependency))
    if is_mac:
        dependency = add(name+'MindMachinePill', 'XCSwiftPackageProductDependency', package=pill_package, productName=quote('MindMachinePill'))
        dependencies.append(dependency)
        links.append(add(name+'MindMachinePilllink', 'PBXBuildFile', productRef=dependency))
    framework_phase = add(name+'frameworks', 'PBXFrameworksBuildPhase', buildActionMask='2147483647', files=array(links), runOnlyForDeploymentPostprocessing='0')
    ext = 'appex' if kind == 'app-extension' else 'app'
    product = add(name+'product', 'PBXFileReference', explicitFileType=quote('wrapper.app-extension' if kind == 'app-extension' else 'wrapper.application'), includeInIndex='0', path=quote(name+'.'+ext), sourceTree='BUILT_PRODUCTS_DIR')
    products.append(product)
    configurations = []
    for config in ['Debug', 'Release']:
        settings = {
            'PRODUCT_NAME':quote(name), 'PRODUCT_BUNDLE_IDENTIFIER':quote(bundle),
            'SWIFT_VERSION':'5.0', 'GENERATE_INFOPLIST_FILE':'NO',
            'ONLY_ACTIVE_ARCH':'YES' if config == 'Debug' else 'NO',
            'INFOPLIST_FILE':quote('Apps/'+folder+'/Info.plist'),
            'CODE_SIGN_STYLE':'Automatic', 'CURRENT_PROJECT_VERSION':'1', 'MARKETING_VERSION':'0.1.0',
            'SDKROOT':'macosx' if is_mac else 'iphoneos',
            'SUPPORTED_PLATFORMS':quote('macosx' if is_mac else 'iphoneos iphonesimulator'),
            'SWIFT_OPTIMIZATION_LEVEL':quote('-Onone' if config == 'Debug' else '-O'),
            'DEBUG_INFORMATION_FORMAT':quote('dwarf' if config == 'Debug' else 'dwarf-with-dsym'),
            'ENABLE_APP_SANDBOX':'YES' if is_mac else 'NO',
            'CODE_SIGN_ENTITLEMENTS':quote('Apps/'+folder+'/Vault.entitlements'),
            'LD_RUNPATH_SEARCH_PATHS':quote('$(inherited) @executable_path/Frameworks'+(' @executable_path/../../Frameworks' if kind == 'app-extension' else '')),
        }
        if kind != 'app-extension': settings['ASSETCATALOG_COMPILER_APPICON_NAME']=quote('AppIcon')
        if is_mac: settings['MACOSX_DEPLOYMENT_TARGET']='14.0'
        else: settings.update(IPHONEOS_DEPLOYMENT_TARGET='17.0', TARGETED_DEVICE_FAMILY=quote('1,2'))
        if kind == 'app-extension': settings.update(APPLICATION_EXTENSION_API_ONLY='YES', SKIP_INSTALL='YES')
        configurations.append(add(name+config, 'XCBuildConfiguration', name=quote(config), baseConfigurationReference=signing_config, buildSettings=dictionary(settings)))
    config_list=add(name+'configs', 'XCConfigurationList', buildConfigurations=array(configurations), defaultConfigurationIsVisible='0', defaultConfigurationName='Release')
    phases = [source_phase, framework_phase, resource_phase]
    target_dependencies = []
    if folder == 'iOS':
        proxy = add('keyboardproxy', 'PBXContainerItemProxy', containerPortal=ident('project'), proxyType='1', remoteGlobalIDString=ident('MindMachineKeyboardtarget'), remoteInfo=quote('MindMachineKeyboard'))
        target_dependencies.append(add('keyboarddependency', 'PBXTargetDependency', target=ident('MindMachineKeyboardtarget'), targetProxy=proxy))
        embed = add('keyboardembedfile', 'PBXBuildFile', fileRef=ident('MindMachineKeyboardproduct'), settings=dictionary({'ATTRIBUTES':array(['RemoveHeadersOnCopy'])}))
        phases.append(add('keyboardembed', 'PBXCopyFilesBuildPhase', buildActionMask='2147483647', dstPath=quote(''), dstSubfolderSpec='13', files=array([embed]), name=quote('Embed Keyboard'), runOnlyForDeploymentPostprocessing='0'))
    targets.append(add(name+'target', 'PBXNativeTarget', buildConfigurationList=config_list, buildPhases=array(phases), buildRules='()', dependencies=array(target_dependencies), name=quote(name), packageProductDependencies=array(dependencies), productName=quote(name), productReference=product, productType=quote('com.apple.product-type.'+kind)))
    # Keep standard bundle version/localization metadata explicit for native
    # discovery. A registered PlugInKit record alone is not Settings availability.
    info = {'CFBundleDisplayName':'Mind Machine' if kind!='app-extension' else 'Mind Machine keyboard',
            'CFBundleExecutable':'$(EXECUTABLE_NAME)', 'CFBundleIdentifier':'$(PRODUCT_BUNDLE_IDENTIFIER)',
            'CFBundleName':'$(PRODUCT_NAME)', 'CFBundleInfoDictionaryVersion':'6.0', 'CFBundleDevelopmentRegion':'en', 'CFBundlePackageType':'XPC!' if kind=='app-extension' else 'APPL',
            'CFBundleShortVersionString':'$(MARKETING_VERSION)', 'CFBundleVersion':'$(CURRENT_PROJECT_VERSION)'}
    info['VaultAppGroup']='$(VAULT_APP_GROUP)'
    info['VaultCloudContainer']='$(VAULT_ICLOUD_CONTAINER)'
    info['VaultKeychainGroup']='$(VAULT_KEYCHAIN_GROUP)'
    if folder=='iOS': info['UIBackgroundModes']=['remote-notification']
    if folder=='iOS': info.update(UILaunchScreen={}, UISupportedInterfaceOrientations=['UIInterfaceOrientationPortrait','UIInterfaceOrientationLandscapeLeft','UIInterfaceOrientationLandscapeRight'])
    if kind=='app-extension':
        info['NSExtension']={'NSExtensionPointIdentifier':'com.apple.keyboard-service',
            'NSExtensionPrincipalClass':'$(PRODUCT_MODULE_NAME).KeyboardViewController',
            'NSExtensionAttributes':{'IsASCIICapable':True,'PrimaryLanguage':'en-US','RequestsOpenAccess':True}}
    if is_mac: info['NSHighResolutionCapable']=True
    # App Store Connect asks about export compliance on every upload. The only cryptography here is Apple's own:
    # CryptoKit AES-GCM for sealed sync revisions, the Security framework Keychain, CloudKit and system SQLite.
    # No third-party or custom cipher ships, so the standard-encryption exemption applies (docs/DESIGN.md, TestFlight delivery).
    info['ITSAppUsesNonExemptEncryption']=False
    # The Mac App Store rejects a Mac app without a category; Productivity matches the product.
    if is_mac: info['LSApplicationCategoryType']='public.app-category.productivity'
    # iPad multitasking validation requires all four orientations on iPad unless the app is full-screen only.
    if folder=='iOS': info['UISupportedInterfaceOrientations~ipad']=['UIInterfaceOrientationPortrait','UIInterfaceOrientationPortraitUpsideDown','UIInterfaceOrientationLandscapeLeft','UIInterfaceOrientationLandscapeRight']
    # Local networking is used only for a deliberately configured inference route.
    info['NSAppTransportSecurity']={'NSAllowsLocalNetworking':True}
    if not is_mac: info['NSLocalNetworkUsageDescription']='Connect to the inference server you configure for chat.'
    (ROOT/'Apps'/folder/'Info.plist').write_bytes(narrated_plist(info, folder + ' bundle metadata read by the OS and DeviceVault/VaultModel.'))
    entitlements={'com.apple.security.app-sandbox':True,'com.apple.security.network.client':True} if is_mac else {'com.apple.security.application-groups':['$(VAULT_APP_GROUP)']}
    entitlements.update({'com.apple.security.application-groups':['$(VAULT_APP_GROUP)'],
        'com.apple.developer.icloud-container-identifiers':['$(VAULT_ICLOUD_CONTAINER)'],
        'com.apple.developer.icloud-services':['CloudKit'],
        'keychain-access-groups':['$(VAULT_KEYCHAIN_GROUP)']})
    if kind != 'app-extension': entitlements['aps-environment' if not is_mac else 'com.apple.developer.aps-environment']='development'
    (ROOT/'Apps'/folder/'Vault.entitlements').write_bytes(narrated_plist(entitlements, folder + ' signing capabilities for shared storage, keys and private CloudKit.'))
    # Shared schemes let xcodebuild reproduce both independent applications.
    if kind != 'app-extension':
        scheme=f'''<?xml version="1.0" encoding="UTF-8"?>
<Scheme LastUpgradeVersion="2620" version="1.3"><BuildAction parallelizeBuildables="YES" buildImplicitDependencies="YES"><BuildActionEntries><BuildActionEntry buildForTesting="YES" buildForRunning="YES" buildForProfiling="YES" buildForArchiving="YES" buildForAnalyzing="YES"><BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="{ident(name+'target')}" BuildableName="{name}.app" BlueprintName="{name}" ReferencedContainer="container:MindMachine.xcodeproj"/></BuildActionEntry></BuildActionEntries></BuildAction><LaunchAction buildConfiguration="Debug" selectedDebuggerIdentifier="Xcode.DebuggerFoundation.Debugger.LLDB" selectedLauncherIdentifier="Xcode.IDEFoundation.Launcher.LLDB" launchStyle="0" useCustomWorkingDirectory="NO" ignoresPersistentStateOnLaunch="NO" debugDocumentVersioning="YES" debugServiceExtension="internal" allowLocationSimulation="YES"><BuildableProductRunnable runnableDebuggingMode="0"><BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="{ident(name+'target')}" BuildableName="{name}.app" BlueprintName="{name}" ReferencedContainer="container:MindMachine.xcodeproj"/></BuildableProductRunnable></LaunchAction></Scheme>
'''
        (ROOT/'MindMachine.xcodeproj/xcshareddata/xcschemes'/f'{name}.xcscheme').write_text(scheme)
product_group=add('products','PBXGroup',name='Products',children=array(products),sourceTree=quote('<group>'))
main_group=add('main','PBXGroup',children=array(groups+[signing_config, product_group]),sourceTree=quote('<group>'))
project_configs=[add('project'+c,'XCBuildConfiguration',name=quote(c),buildSettings=dictionary({'CLANG_ENABLE_MODULES':'YES','SWIFT_VERSION':'5.0'})) for c in ['Debug','Release']]
config_list=add('projectconfigs','XCConfigurationList',buildConfigurations=array(project_configs),defaultConfigurationIsVisible='0',defaultConfigurationName='Release')
project=add('project','PBXProject',attributes=dictionary({'LastUpgradeCheck':'2620'}),buildConfigurationList=config_list,compatibilityVersion=quote('Xcode 14.0'),developmentRegion='en',hasScannedForEncodings='0',knownRegions=array(['en','Base']),mainGroup=main_group,packageReferences=array([package, pill_package]),productRefGroup=product_group,projectDirPath=quote(''),projectRoot=quote(''),targets=array(targets))
# The generated project is committed; regenerating reproduces target membership.
body='\n'.join(f'{key} = '+dictionary(fields)+';' for key,fields in OBJECTS.items())
(ROOT/'MindMachine.xcodeproj/project.pbxproj').write_text('// !$*UTF8*$!\n/* Generated by Scripts/generate_project.py; Xcode builds the three native apps. */\n{ archiveVersion = 1; classes = {}; objectVersion = 56; objects = {\n'+body+'\n}; rootObject = '+project+'; }\n')
